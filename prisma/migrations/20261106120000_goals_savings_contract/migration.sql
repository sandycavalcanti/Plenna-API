-- Fase 1: reconcilia o contrato do cofrinho com o Prisma sem recriar
-- indiscriminadamente o DDL que ja foi aplicado manualmente no Neon.
--
-- Esta migration e deliberadamente fail-fast para drift estrutural. Ela pode
-- ser aplicada a uma base nova apos o baseline ou a uma base que ja contenha
-- a coluna/tabela manualmente criadas. Nao preenche UUIDs de movimentos
-- antigos: se houver movimentos sem a chave, a migration deve parar.

DO $$
DECLARE
  v_column_type text;
  v_column_nullable text;
  v_column_default text;
  v_column_precision integer;
  v_column_scale integer;
  constraint_definition text;
  normalized_definition text;
BEGIN
  IF to_regclass('public.tb_meta') IS NULL THEN
    RAISE EXCEPTION 'GOALS_SCHEMA_DRIFT: public.tb_meta nao existe';
  END IF;

  SELECT c.data_type, c.is_nullable, c.column_default, c.numeric_precision, c.numeric_scale
    INTO v_column_type, v_column_nullable, v_column_default, v_column_precision, v_column_scale
  FROM information_schema.columns AS c
  WHERE c.table_schema = 'public'
    AND c.table_name = 'tb_meta'
    AND c.column_name = 'meta_valor_reservado';

  IF NOT FOUND THEN
    ALTER TABLE public.tb_meta
      ADD COLUMN meta_valor_reservado NUMERIC(10,2) NOT NULL DEFAULT 0;
  ELSIF v_column_type <> 'numeric'
     OR v_column_nullable <> 'NO'
     OR v_column_precision <> 10
     OR v_column_scale <> 2
     OR v_column_default IS NULL
     OR btrim(v_column_default) NOT IN ('0', '0.00') THEN
    RAISE EXCEPTION 'GOALS_SCHEMA_DRIFT: tb_meta.meta_valor_reservado possui definicao incompatível';
  END IF;

  SELECT pg_get_constraintdef(con.oid)
    INTO constraint_definition
  FROM pg_constraint con
  JOIN pg_class rel ON rel.oid = con.conrelid
  JOIN pg_namespace nsp ON nsp.oid = rel.relnamespace
  WHERE nsp.nspname = 'public'
    AND rel.relname = 'tb_meta'
    AND con.conname = 'chk_meta_valor_reservado';

  IF NOT FOUND THEN
    ALTER TABLE public.tb_meta
      ADD CONSTRAINT chk_meta_valor_reservado
      CHECK (meta_valor_reservado >= 0);
  ELSE
    normalized_definition := lower(replace(replace(replace(constraint_definition, ' ', ''), '(', ''), ')', ''));
    IF normalized_definition NOT LIKE '%meta_valor_reservado>=0%' THEN
      RAISE EXCEPTION 'GOALS_SCHEMA_DRIFT: chk_meta_valor_reservado possui definicao incompatível';
    END IF;
  END IF;
END $$;

DO $$
DECLARE
  movement_count bigint;
  constraint_definition text;
  index_definition text;
  normalized_definition text;
  compact_definition text;
BEGIN
  IF to_regclass('public.tb_meta_movimentacao') IS NULL THEN
    CREATE TABLE public.tb_meta_movimentacao (
      meta_movimentacao_id          INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
      meta_id                       INTEGER NOT NULL,
      meta_movimentacao_operacao_id UUID NOT NULL,
      meta_movimentacao_tipo        VARCHAR(10) NOT NULL,
      meta_movimentacao_valor       NUMERIC(10,2) NOT NULL,
      meta_movimentacao_data        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      CONSTRAINT tb_meta_movimentacao_pkey PRIMARY KEY (meta_movimentacao_id),
      CONSTRAINT fk_meta_movimentacao_meta
        FOREIGN KEY (meta_id) REFERENCES public.tb_meta(meta_id)
        ON DELETE CASCADE ON UPDATE NO ACTION,
      CONSTRAINT chk_meta_movimentacao_tipo
        CHECK (meta_movimentacao_tipo IN ('DEPOSITO', 'RETIRADA')),
      CONSTRAINT chk_meta_movimentacao_valor
        CHECK (meta_movimentacao_valor > 0),
      CONSTRAINT uq_meta_movimentacao_meta_operacao
        UNIQUE (meta_id, meta_movimentacao_operacao_id)
    );
  ELSE
    IF NOT EXISTS (
      SELECT 1
      FROM information_schema.columns AS c
      WHERE c.table_schema = 'public'
        AND c.table_name = 'tb_meta_movimentacao'
        AND c.column_name = 'meta_movimentacao_operacao_id'
    ) THEN
      SELECT count(*) INTO movement_count FROM public.tb_meta_movimentacao;
      IF movement_count > 0 THEN
        RAISE EXCEPTION 'GOALS_IDEMPOTENCY_BLOCKED: % movimentos antigos sem UUID de operação', movement_count;
      END IF;
      ALTER TABLE public.tb_meta_movimentacao
        ADD COLUMN meta_movimentacao_operacao_id UUID NOT NULL;
    END IF;

    IF EXISTS (
      SELECT 1
      FROM (VALUES
        ('meta_movimentacao_id'),
        ('meta_id'),
        ('meta_movimentacao_operacao_id'),
        ('meta_movimentacao_tipo'),
        ('meta_movimentacao_valor'),
        ('meta_movimentacao_data')
      ) AS required_columns(column_name)
      WHERE NOT EXISTS (
        SELECT 1
        FROM information_schema.columns AS c
        WHERE c.table_schema = 'public'
          AND c.table_name = 'tb_meta_movimentacao'
          AND c.column_name = required_columns.column_name
      )
    ) THEN
      RAISE EXCEPTION 'GOALS_SCHEMA_DRIFT: tb_meta_movimentacao possui coluna obrigatoria ausente';
    END IF;

    IF NOT EXISTS (
      SELECT 1
      FROM pg_attribute attr
      JOIN pg_class rel ON rel.oid = attr.attrelid
      JOIN pg_namespace nsp ON nsp.oid = rel.relnamespace
      WHERE nsp.nspname = 'public'
        AND rel.relname = 'tb_meta_movimentacao'
        AND attr.attname = 'meta_movimentacao_id'
        AND attr.attidentity IN ('a', 'd')
        AND attr.attnum > 0
        AND NOT attr.attisdropped
    ) THEN
      RAISE EXCEPTION 'GOALS_SCHEMA_DRIFT: meta_movimentacao_id nao e uma coluna identity';
    END IF;

    IF EXISTS (
      SELECT 1
      FROM information_schema.columns AS c
      WHERE c.table_schema = 'public'
        AND c.table_name = 'tb_meta_movimentacao'
        AND (
          (c.column_name = 'meta_movimentacao_id' AND (c.data_type <> 'integer' OR c.is_nullable <> 'NO')) OR
          (c.column_name = 'meta_id' AND (c.data_type <> 'integer' OR c.is_nullable <> 'NO')) OR
          (c.column_name = 'meta_movimentacao_operacao_id' AND (c.udt_name <> 'uuid' OR c.is_nullable <> 'NO')) OR
          (c.column_name = 'meta_movimentacao_tipo' AND (c.data_type <> 'character varying' OR c.character_maximum_length <> 10 OR c.is_nullable <> 'NO')) OR
          (c.column_name = 'meta_movimentacao_valor' AND (c.data_type <> 'numeric' OR c.numeric_precision <> 10 OR c.numeric_scale <> 2 OR c.is_nullable <> 'NO')) OR
          (c.column_name = 'meta_movimentacao_data' AND (c.udt_name <> 'timestamptz' OR c.is_nullable <> 'NO' OR c.column_default IS NULL))
        )
    ) THEN
      RAISE EXCEPTION 'GOALS_SCHEMA_DRIFT: tb_meta_movimentacao possui coluna incompatível';
    END IF;
  END IF;

  SELECT pg_get_constraintdef(con.oid)
    INTO constraint_definition
  FROM pg_constraint con
  JOIN pg_class rel ON rel.oid = con.conrelid
  JOIN pg_namespace nsp ON nsp.oid = rel.relnamespace
  WHERE nsp.nspname = 'public'
    AND rel.relname = 'tb_meta_movimentacao'
    AND con.conname = 'fk_meta_movimentacao_meta';

  IF NOT FOUND THEN
    ALTER TABLE public.tb_meta_movimentacao
      ADD CONSTRAINT fk_meta_movimentacao_meta
      FOREIGN KEY (meta_id) REFERENCES public.tb_meta(meta_id)
      ON DELETE CASCADE ON UPDATE NO ACTION;
  ELSE
    compact_definition := lower(regexp_replace(constraint_definition, '\s+', '', 'g'));
    IF compact_definition NOT LIKE '%foreignkey(meta_id)%references%tb_meta(meta_id)%ondeletecascade%' THEN
      RAISE EXCEPTION 'GOALS_SCHEMA_DRIFT: fk_meta_movimentacao_meta possui definicao incompatível';
    END IF;
  END IF;

  SELECT pg_get_constraintdef(con.oid)
    INTO constraint_definition
  FROM pg_constraint con
  JOIN pg_class rel ON rel.oid = con.conrelid
  JOIN pg_namespace nsp ON nsp.oid = rel.relnamespace
  WHERE nsp.nspname = 'public'
    AND rel.relname = 'tb_meta_movimentacao'
    AND con.conname = 'chk_meta_movimentacao_tipo';

  IF NOT FOUND THEN
    ALTER TABLE public.tb_meta_movimentacao
      ADD CONSTRAINT chk_meta_movimentacao_tipo
      CHECK (meta_movimentacao_tipo IN ('DEPOSITO', 'RETIRADA'));
  ELSE
    normalized_definition := lower(replace(replace(replace(constraint_definition, ' ', ''), '(', ''), ')', ''));
    IF normalized_definition NOT LIKE '%meta_movimentacao_tipo%deposito%retirada%' THEN
      RAISE EXCEPTION 'GOALS_SCHEMA_DRIFT: chk_meta_movimentacao_tipo possui definicao incompatível';
    END IF;
  END IF;

  SELECT pg_get_constraintdef(con.oid)
    INTO constraint_definition
  FROM pg_constraint con
  JOIN pg_class rel ON rel.oid = con.conrelid
  JOIN pg_namespace nsp ON nsp.oid = rel.relnamespace
  WHERE nsp.nspname = 'public'
    AND rel.relname = 'tb_meta_movimentacao'
    AND con.conname = 'chk_meta_movimentacao_valor';

  IF NOT FOUND THEN
    ALTER TABLE public.tb_meta_movimentacao
      ADD CONSTRAINT chk_meta_movimentacao_valor
      CHECK (meta_movimentacao_valor > 0);
  ELSE
    normalized_definition := lower(replace(replace(replace(constraint_definition, ' ', ''), '(', ''), ')', ''));
    IF normalized_definition NOT LIKE '%meta_movimentacao_valor>0%' THEN
      RAISE EXCEPTION 'GOALS_SCHEMA_DRIFT: chk_meta_movimentacao_valor possui definicao incompatível';
    END IF;
  END IF;

  SELECT pg_get_constraintdef(con.oid)
    INTO constraint_definition
  FROM pg_constraint con
  JOIN pg_class rel ON rel.oid = con.conrelid
  JOIN pg_namespace nsp ON nsp.oid = rel.relnamespace
  WHERE nsp.nspname = 'public'
    AND rel.relname = 'tb_meta_movimentacao'
    AND con.conname = 'uq_meta_movimentacao_meta_operacao';

  IF NOT FOUND THEN
    ALTER TABLE public.tb_meta_movimentacao
      ADD CONSTRAINT uq_meta_movimentacao_meta_operacao
      UNIQUE (meta_id, meta_movimentacao_operacao_id);
  ELSE
    compact_definition := lower(regexp_replace(constraint_definition, '\s+', '', 'g'));
    IF compact_definition NOT LIKE '%unique(meta_id,meta_movimentacao_operacao_id)%' THEN
      RAISE EXCEPTION 'GOALS_SCHEMA_DRIFT: uq_meta_movimentacao_meta_operacao possui definicao incompatível';
    END IF;
  END IF;

  SELECT idx.indexdef
    INTO index_definition
  FROM pg_indexes AS idx
  WHERE idx.schemaname = 'public'
    AND idx.tablename = 'tb_meta_movimentacao'
    AND idx.indexname = 'idx_meta_movimentacao_meta_data';

  IF NOT FOUND THEN
    CREATE INDEX idx_meta_movimentacao_meta_data
      ON public.tb_meta_movimentacao (meta_id, meta_movimentacao_data DESC, meta_movimentacao_id DESC);
  ELSE
    normalized_definition := lower(replace(index_definition, ' ', ''));
    IF normalized_definition NOT LIKE '%(meta_id,meta_movimentacao_data desc,meta_movimentacao_id desc)%'
       AND normalized_definition NOT LIKE '%(meta_id,meta_movimentacao_datadesc,meta_movimentacao_iddesc)%' THEN
      RAISE EXCEPTION 'GOALS_SCHEMA_DRIFT: idx_meta_movimentacao_meta_data possui definicao incompatível';
    END IF;
  END IF;
END $$;
